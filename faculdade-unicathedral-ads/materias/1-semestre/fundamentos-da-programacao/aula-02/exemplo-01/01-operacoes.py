#Entrada de dados.
n1 = float(input("Digite um valor: "))
n2 = float(input("Digite outro valor: "))

#Processamento de dados.
adi = n1 + n2
sub = n1 - n2
mult = n1 * n2
divi = n1 / n2

#Saída de dados
print(f"Adição = {adi}")
print(f"Subtração = {sub}")
print(f"Multiplicação = {mult}")
print(f"Divisão = {divi}")