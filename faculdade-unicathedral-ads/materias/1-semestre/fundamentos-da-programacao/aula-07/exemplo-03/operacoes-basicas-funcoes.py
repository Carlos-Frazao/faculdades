def adição(a, b):
        return a + b
def subtração(a, b):
        return a - b
def multiplicação(a, b):
        return a * b
def divisão(a, b):
        return a / b

a = 5
b = 6

print(f"Soma: {adição(a, b)}")
print(f"Subtração: {subtração(a, b)}")
print(f"Multiplicação: {multiplicação(a, b)}")
print(f"Divisão: {divisão(a, b)}")
